// The household inventory page, generated from the store and never edited by hand.
import { listItems, LOCATIONS, STORE } from './store.mjs';

export const ROLLUP_PATH = 'knowledge/wiki/household/current-inventory.md';
const title = (text) => text.charAt(0).toUpperCase() + text.slice(1).replaceAll('_', ' ');
const plain = (text) => String(text).replace(/[\\`*_[\]()<>#!|]/g, '\\$&').replace(/\s+/g, ' ');

function itemLine(item) {
  const expires = item.expires ? ` (expires ${item.expires})` : '';
  return `- ${plain(item.name)}: ${item.amount} ${plain(item.unit)}${expires}`;
}

function sections(items) {
  const lines = [];
  for (const location of LOCATIONS) {
    const here = items.filter((item) => item.location === location);
    if (!here.length) continue;
    lines.push(`## ${title(location)}`, '');
    for (const category of [...new Set(here.map((item) => item.category))].sort()) {
      lines.push(`### ${title(category)}`, '', ...here.filter((i) => i.category === category).sort((a, b) => a.key.localeCompare(b.key)).map(itemLine), '');
    }
  }
  return lines;
}

export function renderRollup(inventory) {
  const items = listItems(inventory);
  const body = [
    '# Current inventory',
    '',
    'Generated by chef-food-inventory from the inventory store. Do not edit this page; ask Chef to change inventory.',
    '',
    ...(items.length ? sections(items) : ['No items.', '']),
  ].join('\n');
  return {
    slug: 'current-inventory',
    frontmatter: { type: 'inventory-rollup', title: 'Current inventory', generated_from: STORE.inventory, updated: inventory.lastUpdated.slice(0, 10) },
    body,
  };
}
